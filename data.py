def classify_material(isotope: str, activity_tbq: float, use_type: str = "") -> dict:
    """จำแนกประเภทวัสดุกัมมันตรังสี พร้อมระบุแหล่งที่มาของค่า D"""
    if use_type and use_type in USE_TYPE_CATEGORY:
        cat = USE_TYPE_CATEGORY[use_type]
        return {
            "category": cat, "method": "use_table",
            "detail": f"จำแนกจากตารางการใช้ประโยชน์",
            "use_type": use_type, "ad_ratio": None,
            "d_value": None, "d_source": "ปส.", "d_note": "",
            "activity_tbq": activity_tbq,
            "threshold": CATEGORY_THRESHOLDS[cat][2],
        }

    d_value, d_source, d_note = get_d_value(isotope)
    if not d_value or not activity_tbq or activity_tbq <= 0:
        return {
            "category": None, "method": "unknown",
            "detail": "ข้อมูลไม่เพียงพอ",
            "d_source": d_source, "d_note": d_note,
        }

    ad_ratio = activity_tbq / d_value
    cat = classify_by_ad(ad_ratio)
    return {
        "category": cat, "method": "ad_ratio",
        "detail": (f"A = {activity_tbq:.3e} TBq | "
                   f"D = {d_value:.2e} TBq | "
                   f"A/D = {ad_ratio:.3f}"),
        "use_type": use_type, "ad_ratio": ad_ratio,
        "d_value": d_value, "d_source": d_source, "d_note": d_note,
        "activity_tbq": activity_tbq,
        "threshold": CATEGORY_THRESHOLDS[cat][2],
    }
